import AppKit

/// Borrows a pasteboard: snapshots every item and type, lets uttr write or
/// observe a copy, then puts the original back unless something newer landed.
struct ClipboardTransaction {
    typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private let pasteboard: NSPasteboard
    private let snapshot: Snapshot
    private(set) var ownChangeCount: Int?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
        self.snapshot = (pasteboard.pasteboardItems ?? []).map { item in
            var copy: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { copy[type] = data }
            }
            return copy
        }
    }

    /// Writes uttr's own text, marked so clipboard managers skip it.
    mutating func write(_ text: String) -> Bool {
        pasteboard.clearContents()
        ownChangeCount = pasteboard.changeCount
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return false }
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        guard pasteboard.writeObjects([item]) else { return false }
        ownChangeCount = pasteboard.changeCount
        return true
    }

    /// Restores if the board is still at uttr's own write.
    @discardableResult
    func restore() -> Bool {
        guard let ownChangeCount else { return false }
        return restore(ifChangeCountIs: ownChangeCount)
    }

    /// Restores if the board is still at `expected`, e.g. another app's copy that uttr triggered.
    @discardableResult
    func restore(ifChangeCountIs expected: Int) -> Bool {
        guard Self.shouldRestore(current: pasteboard.changeCount, expected: expected) else { return false }
        pasteboard.clearContents()
        let items = snapshot.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in entries { item.setData(data, forType: type) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
        return true
    }

    nonisolated static func shouldRestore(current: Int, expected: Int) -> Bool {
        current == expected
    }
}
