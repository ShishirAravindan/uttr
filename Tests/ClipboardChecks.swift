import AppKit

/// Restore rules and snapshot round-trips on a private pasteboard, never the general one.
@main
struct ClipboardChecks {
    static func main() {
        precondition(ClipboardTransaction.shouldRestore(current: 5, expected: 5))
        precondition(!ClipboardTransaction.shouldRestore(current: 6, expected: 5))

        let board = NSPasteboard(name: NSPasteboard.Name("uttr.clipboard-checks.\(UUID().uuidString)"))
        defer { board.releaseGlobally() }

        let png = Data([0x89, 0x50, 0x4E, 0x47, 0x00, 0xFF, 0x10])
        let concealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
        func seed() {
            board.clearContents()
            let first = NSPasteboardItem()
            first.setString("rich", forType: .string)
            first.setData(Data("<b>rich</b>".utf8), forType: .html)
            first.setData(png, forType: .png)
            first.setData(Data(), forType: concealed)
            let second = NSPasteboardItem()
            second.setString("second", forType: .string)
            board.writeObjects([first, second])
        }
        func dump() -> [[String: Data]] {
            (board.pasteboardItems ?? []).map { item in
                Dictionary(uniqueKeysWithValues: item.types.compactMap { t in
                    item.data(forType: t).map { (t.rawValue, $0) }
                })
            }
        }

        // Multi-item, multi-type, binary and concealed data survive a paste.
        seed()
        let original = dump()
        var tx = ClipboardTransaction(pasteboard: board)
        precondition(tx.write("dictated"))
        precondition(board.string(forType: .string) == "dictated")
        let types = board.pasteboardItems?.first?.types ?? []
        precondition(types.contains(ClipboardTransaction.transientType))
        precondition(types.contains(ClipboardTransaction.autoGeneratedType))
        precondition(tx.restore())
        precondition(dump() == original, "round trip")

        // A copy made after uttr's write is left alone.
        var late = ClipboardTransaction(pasteboard: board)
        precondition(late.write("dictated"))
        board.clearContents()
        board.setString("user copy", forType: .string)
        precondition(!late.restore())
        precondition(board.string(forType: .string) == "user copy")

        // An empty clipboard is restored to empty, not left holding uttr's text.
        board.clearContents()
        var empty = ClipboardTransaction(pasteboard: board)
        precondition(empty.write("dictated"))
        precondition(empty.restore())
        precondition(board.pasteboardItems?.isEmpty ?? true)

        // Observed copies (selection reading) restore only at the observed count.
        seed()
        let seeded = dump()
        let observer = ClipboardTransaction(pasteboard: board)
        board.clearContents()
        board.setString("selection", forType: .string)
        let observed = board.changeCount
        precondition(observer.restore(ifChangeCountIs: observed))
        precondition(dump() == seeded)
        let stale = ClipboardTransaction(pasteboard: board)
        board.clearContents()
        board.setString("selection", forType: .string)
        let seen = board.changeCount
        board.clearContents()
        board.setString("newer", forType: .string)
        precondition(!stale.restore(ifChangeCountIs: seen))
        precondition(board.string(forType: .string) == "newer")

        // Two transactions keep separate snapshots.
        seed()
        var a = ClipboardTransaction(pasteboard: board)
        precondition(a.write("one"))
        precondition(a.restore())
        precondition(dump() == seeded)
        board.clearContents()
        board.setString("other", forType: .string)
        var b = ClipboardTransaction(pasteboard: board)
        precondition(b.write("two"))
        precondition(b.restore())
        precondition(board.string(forType: .string) == "other")
        precondition(a.restore(ifChangeCountIs: board.changeCount))
        precondition(dump() == seeded)

        print("Clipboard checks passed")
    }
}
